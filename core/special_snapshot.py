def normalize_snapshot(supplier_id: str) -> dict:
    """把样本数据补齐为与实时抓取一致的完整结构。"""
    item = SNAPSHOT.get(supplier_id)
    if not item:
        return {}
    ent = dict(item.get("enterprise") or {})
    recs = []
    for r in item.get("records") or []:
        rec = {
            "tender_id": r.get("tender_id", ""),
            "title": r.get("title", ""),
            "info_type": r.get("info_type", ""),
            "status": r.get("status", ""),
            "region": r.get("region", ""),
            "buyer": r.get("buyer", ""),
            "winner": r.get("winner", ent.get("name", "")),
            "bid_type": r.get("bid_type", ""),
            "method": r.get("method", ""),
            "project_no": r.get("project_no", ""),
            "amount": float(r.get("amount") or 0),
            "publish_date": r.get("publish_date", ""),
            "products": r.get("products") or [],
            "industry": r.get("industry", ""),
            "role": "中标单位",
            "_snapshot": True,
        }
        recs.append(rec)

    # 派生标记（与实时路径保持同一套判定逻辑，避免两处口径漂移）
    from core.outsourcing_special import _is_fin, _is_outsource, NON_COMPETITIVE
    for rec in recs:
        rec["buyer_is_fin"] = _is_fin(rec["buyer"])
        txt = f"{rec['title']} {' '.join(str(x) for x in rec['products'])}"
        rec["is_outsource"] = _is_outsource(txt)
        rec["non_competitive"] = rec["method"] in NON_COMPETITIVE

    return {
        "ok": True,
        "supplier": ent.get("name", ""),
        "supplier_id": supplier_id,
        "enterprise": ent,
        "records": recs,
        "error": "",
        "query_summary": {
            "命中总数": ent.get("as_winner", len(recs)),
            "结果说明": "离线样本（演示兜底数据）",
            "企业名称": ent.get("name", ""),
        },
        "total_hits": ent.get("as_winner", len(recs)),
        "offline": True,
    }


def has_snapshot(supplier_id: str) -> bool:
    return supplier_id in SNAPSHOT
